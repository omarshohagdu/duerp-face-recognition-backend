-- =====================================================================
-- Employee office geo-locations with admin approval
--
-- Spec: docs/employee_attendance_face_api.md. Routes: src/routes/geo_location.rs.
--
-- WHAT THIS ADDS
--   attendance.geo_location_office            admin-defined geo points per office
--   attendance.employee_geo_location          an employee's selected points + approval state
--   attendance.employee_geo_location_audit    every request / approve / reject / revoke / remove / assign
--   attendance.geo_location_office_audit      every create / coordinate change / status change of a point
--   attendance.geo_attendance_attempt_log     failed location checks on /verify
--   + four nullable columns on wow_attendance_records saying WHERE a check-in matched
--   + the functions every route calls, and the gate /verify calls
--
-- HOW THE SPEC MAPS ONTO THIS DATABASE
--   * The spec's `office` table is `ictcell.body`; `office_id` holds
--     `body.body_code` ("490010"), the same code `employees.office` holds and
--     `body_building_mapping` is keyed on. `ictcell.body.body_code` carries no
--     unique constraint, so there is no FK — existence is checked on write.
--   * `employee_id` is `employees.emp_id`, which is also the bearer token's
--     `sub` for staff (src/routes/auth.rs).
--   * MySQL ENUMs are varchar + CHECK; DATETIME is timestamptz.
--   * Face matching is NOT done here: /verify already identifies the person
--     through the AI platform. Only the LOCATION half of "mark attendance"
--     changes — see `attendance.employee_geo_location_verify` (§6).
--
-- ROLLOUT — WHY NOTHING BREAKS ON DEPLOY
--   The /verify gate is chosen by the `GEO_LOCATION_MODE` setting:
--     BODY_MAPPING                      the old rule only (employees.office -> buildings)
--     APPROVED_OFFICE                   the spec's rule only: no APPROVED office = no attendance
--     APPROVED_OFFICE_OR_BODY_MAPPING   (seeded) the spec's rule for every employee who has
--                                       at least one APPROVED selection; the old rule for
--                                       everyone else, so staff keep checking in while
--                                       their selections are being approved
--   Flip to APPROVED_OFFICE once approvals are done:
--     UPDATE attendance.system_settings SET value = 'APPROVED_OFFICE', updated_at = now()
--      WHERE key = 'GEO_LOCATION_MODE';
--
-- Idempotent: IF NOT EXISTS / CREATE OR REPLACE / guarded INSERTs throughout.
-- Requires 006 (access control), 008 (system_settings).
--
--     psql "$DATABASE_URL" -f sql/010_employee_geo_location.sql
--     cargo test --test employee_geo_location_sql
--
-- ROLL BACK (nothing outside this file references these):
--     ALTER TABLE attendance.wow_attendance_records
--         DROP COLUMN IF EXISTS employee_geo_location_id,
--         DROP COLUMN IF EXISTS geo_location_office_id,
--         DROP COLUMN IF EXISTS latitude, DROP COLUMN IF EXISTS longitude,
--         DROP COLUMN IF EXISTS distance_meters;
--     DROP TABLE IF EXISTS attendance.geo_attendance_attempt_log,
--                          attendance.employee_geo_location_audit,
--                          attendance.geo_location_office_audit,
--                          attendance.employee_geo_location,
--                          attendance.geo_location_office CASCADE;
--   and switch the /verify gate back first, or it 500s:
--     UPDATE attendance.system_settings SET value = 'BODY_MAPPING' WHERE key = 'GEO_LOCATION_MODE';
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS attendance;

-- ---------------------------------------------------------------------
-- 1 · Tables
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS attendance.geo_location_office (
    id             bigint        PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    office_id      varchar(50)   NOT NULL,          -- ictcell.body.body_code
    -- Optional: tells two points of one office apart ("Building 2"). The
    -- employee sees the office name, then this.
    label          varchar(255),
    latitude       numeric(10,7) NOT NULL CHECK (latitude  BETWEEN  -90 AND  90),
    longitude      numeric(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    radius_meters  integer       NOT NULL DEFAULT 100 CHECK (radius_meters BETWEEN 30 AND 1000),
    status         varchar(16)   NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_by     varchar(50),
    created_at     timestamptz   NOT NULL DEFAULT now(),
    updated_at     timestamptz   NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS geo_location_office_office_status_idx
    ON attendance.geo_location_office (office_id, status);

COMMENT ON TABLE attendance.geo_location_office IS
    'Admin-defined geo points of an office (office_id = ictcell.body.body_code). Only ACTIVE points are selectable and count for attendance.';

CREATE TABLE IF NOT EXISTS attendance.employee_geo_location (
    id                      bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    employee_id             varchar(50)  NOT NULL,   -- employees.emp_id
    geo_location_office_id  bigint       NOT NULL
                            REFERENCES attendance.geo_location_office(id),
    status        varchar(16)  NOT NULL DEFAULT 'PENDING'
                  CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'REVOKED', 'REMOVED')),
    requested_at  timestamptz  NOT NULL DEFAULT now(),
    reviewed_by   varchar(50),
    reviewed_at   timestamptz,
    review_note   varchar(255),
    CONSTRAINT employee_geo_location_uq UNIQUE (employee_id, geo_location_office_id)
);

CREATE INDEX IF NOT EXISTS employee_geo_location_emp_status_idx
    ON attendance.employee_geo_location (employee_id, status);
CREATE INDEX IF NOT EXISTS employee_geo_location_status_idx
    ON attendance.employee_geo_location (status, requested_at);

COMMENT ON TABLE attendance.employee_geo_location IS
    'Offices an employee selected. Counts for attendance only when APPROVED and the point is ACTIVE.';

CREATE TABLE IF NOT EXISTS attendance.employee_geo_location_audit (
    id                        bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    employee_geo_location_id  bigint      NOT NULL
                              REFERENCES attendance.employee_geo_location(id) ON DELETE CASCADE,
    -- Who did it: the admin for APPROVE/REJECT/REVOKE/ASSIGN, the employee for REQUEST/REMOVE.
    actor_id    varchar(50),
    action      varchar(16) NOT NULL
                CHECK (action IN ('REQUEST', 'APPROVE', 'REJECT', 'REVOKE', 'REMOVE', 'ASSIGN')),
    old_status  varchar(16),
    new_status  varchar(16) NOT NULL,
    note        varchar(255),
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS employee_geo_location_audit_row_idx
    ON attendance.employee_geo_location_audit (employee_geo_location_id, created_at DESC);

CREATE TABLE IF NOT EXISTS attendance.geo_location_office_audit (
    id                      bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    geo_location_office_id  bigint      NOT NULL
                            REFERENCES attendance.geo_location_office(id) ON DELETE CASCADE,
    actor_id    varchar(50),
    action      varchar(16) NOT NULL CHECK (action IN ('CREATE', 'UPDATE', 'STATUS')),
    old_value   jsonb,
    new_value   jsonb,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS geo_location_office_audit_row_idx
    ON attendance.geo_location_office_audit (geo_location_office_id, created_at DESC);

-- Failed location checks only: a successful one is the attendance record.
CREATE TABLE IF NOT EXISTS attendance.geo_attendance_attempt_log (
    id                              bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    employee_id                     varchar(50) NOT NULL,
    result                          varchar(16) NOT NULL DEFAULT 'FAILED',
    failure_code                    varchar(64),
    nearest_geo_location_office_id  bigint,
    distance_meters                 numeric(12,2),
    latitude                        double precision,
    longitude                       double precision,
    accuracy_meters                 double precision,
    created_at                      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS geo_attendance_attempt_log_emp_idx
    ON attendance.geo_attendance_attempt_log (employee_id, created_at DESC);

-- Where a check-in matched. Nullable: students, and employees checked by the
-- old body mapping, have no employee_geo_location row. Adding nullable columns
-- with no default is a catalogue-only change — no table rewrite.
ALTER TABLE attendance.wow_attendance_records
    ADD COLUMN IF NOT EXISTS employee_geo_location_id bigint,
    ADD COLUMN IF NOT EXISTS geo_location_office_id   bigint,
    ADD COLUMN IF NOT EXISTS latitude                 double precision,
    ADD COLUMN IF NOT EXISTS longitude                double precision,
    ADD COLUMN IF NOT EXISTS distance_meters          numeric(12,2);

