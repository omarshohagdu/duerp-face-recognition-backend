INSERT INTO attendance.system_settings (key, value, label)
SELECT v.key, v.value, v.label
  FROM (VALUES
    ('GEO_LOCATION_MODE', 'APPROVED_OFFICE_OR_BODY_MAPPING',
        'Which offices /verify checks: BODY_MAPPING | APPROVED_OFFICE | APPROVED_OFFICE_OR_BODY_MAPPING'),
    ('GEO_MAX_ACTIVE_LOCATIONS', '5',
        'Most PENDING + APPROVED offices one employee may hold'),
    ('GEO_MAX_GPS_ACCURACY_METERS', '50',
        'Reject a check-in whose reported GPS accuracy is worse than this (only when the device reports it)')
  ) AS v(key, value, label)
 WHERE NOT EXISTS (SELECT 1 FROM attendance.system_settings s WHERE s.key = v.key);

CREATE OR REPLACE FUNCTION attendance.geo_setting_int(p_key varchar, p_default integer)
RETURNS integer
LANGUAGE sql STABLE
AS $$
    SELECT COALESCE(
        (SELECT CASE WHEN btrim(value) ~ '^[0-9]+$' THEN btrim(value)::integer END
           FROM attendance.system_settings WHERE key = p_key),
        p_default);
$$;

CREATE OR REPLACE FUNCTION attendance.geo_location_mode()
RETURNS varchar
LANGUAGE sql STABLE
AS $$
    SELECT CASE upper(btrim(COALESCE(
                    (SELECT value FROM attendance.system_settings WHERE key = 'GEO_LOCATION_MODE'), '')))
             WHEN 'BODY_MAPPING'    THEN 'BODY_MAPPING'
             WHEN 'APPROVED_OFFICE' THEN 'APPROVED_OFFICE'
             -- Anything unset or misspelt is the fallback mode: it never locks
             -- out an employee the old rule would have let in.
             ELSE 'APPROVED_OFFICE_OR_BODY_MAPPING'
           END;
$$;

