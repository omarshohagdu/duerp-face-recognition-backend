-- The house envelope (same as sql/007): `status` + `code` + `message` + `data`.
CREATE OR REPLACE FUNCTION attendance.geo_fail(p_code text, p_message text, p_data jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE sql IMMUTABLE
AS $$
    SELECT jsonb_build_object('status', 'failed', 'code', p_code, 'message', p_message,
                              'data', COALESCE(p_data, '{}'::jsonb));
$$;

CREATE OR REPLACE FUNCTION attendance.geo_ok(p_message text, p_data jsonb)
RETURNS jsonb
LANGUAGE sql IMMUTABLE
AS $$
    SELECT jsonb_build_object('status', 'success', 'message', p_message, 'data', p_data);
$$;

-- Great-circle distance in metres. `least(1, …)` keeps asin() in its domain
-- when float error pushes the argument a hair over 1 (device exactly on the point).
CREATE OR REPLACE FUNCTION attendance.haversine_meters(
    lat1 double precision, lon1 double precision,
    lat2 double precision, lon2 double precision
) RETURNS double precision
LANGUAGE sql IMMUTABLE STRICT
AS $$
    SELECT 2 * 6371000 * asin(least(1, sqrt(
        power(sin(radians(lat2 - lat1) / 2), 2) +
        cos(radians(lat1)) * cos(radians(lat2)) *
        power(sin(radians(lon2 - lon1) / 2), 2))));
$$;

-- One geo point as every response shows it.
CREATE OR REPLACE FUNCTION attendance.geo_office_json(p_id bigint)
RETURNS jsonb
LANGUAGE sql STABLE
AS $$
    SELECT jsonb_build_object(
        'id',            g.id,
        'office_id',     g.office_id,
        'office_name',   b.name,
        'label',         g.label,
        'latitude',      g.latitude::double precision,
        'longitude',     g.longitude::double precision,
        'radius_meters', g.radius_meters,
        'status',        g.status,
        'created_by',    g.created_by,
        'created_at',    g.created_at,
        'updated_at',    g.updated_at)
      FROM attendance.geo_location_office g
      LEFT JOIN LATERAL (SELECT name FROM ictcell.body WHERE body_code = g.office_id LIMIT 1) b ON true
     WHERE g.id = p_id;
$$;

-- One employee selection as every response shows it.
CREATE OR REPLACE FUNCTION attendance.employee_geo_location_json(p_id bigint)
RETURNS jsonb
LANGUAGE sql STABLE
AS $$
    SELECT jsonb_build_object(
        'id',                     egl.id,
        'employee_id',            egl.employee_id,
        'employee_name',          e.name_en,
        'designation',            e.designation_en,
        'department',             eb.name,
        'geo_location_office_id', g.id,
        'office_id',              g.office_id,
        'office_name',            b.name,
        'label',                  g.label,
        'latitude',               g.latitude::double precision,
        'longitude',              g.longitude::double precision,
        'radius_meters',          g.radius_meters,
        'office_status',          g.status,
        'status',                 egl.status,
        'requested_at',           egl.requested_at,
        'reviewed_by',            egl.reviewed_by,
        'reviewed_at',            egl.reviewed_at,
        'review_note',            egl.review_note)
      FROM attendance.employee_geo_location egl
      JOIN attendance.geo_location_office g ON g.id = egl.geo_location_office_id
      LEFT JOIN LATERAL (SELECT name FROM ictcell.body WHERE body_code = g.office_id LIMIT 1) b ON true
      LEFT JOIN LATERAL (SELECT name_en, designation_en, office
                           FROM attendance.employees WHERE emp_id = egl.employee_id LIMIT 1) e ON true
      LEFT JOIN LATERAL (SELECT name FROM ictcell.body WHERE body_code = e.office LIMIT 1) eb ON true
     WHERE egl.id = p_id;
$$;

