CREATE OR REPLACE FUNCTION attendance.employee_geo_remove(
    p_employee_id varchar,
    p_id          bigint
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_emp varchar := btrim(COALESCE(p_employee_id, ''));
    v_old varchar;
BEGIN
    -- Scoped to the caller: somebody else's row reads as "not found", never as
    -- "not yours", so ids cannot be probed.
    SELECT status INTO v_old FROM attendance.employee_geo_location
     WHERE id = p_id AND employee_id = v_emp FOR UPDATE;
    IF NOT FOUND THEN
        RETURN attendance.geo_fail('NOT_FOUND', format('Office selection %s not found', p_id));
    END IF;
    IF v_old NOT IN ('PENDING', 'APPROVED') THEN
        RETURN attendance.geo_fail('INVALID_STATUS_TRANSITION',
            format('A %s selection cannot be removed', v_old), jsonb_build_object('status', v_old));
    END IF;

    UPDATE attendance.employee_geo_location SET status = 'REMOVED' WHERE id = p_id;
    INSERT INTO attendance.employee_geo_location_audit
                (employee_geo_location_id, actor_id, action, old_status, new_status)
         VALUES (p_id, v_emp, 'REMOVE', v_old, 'REMOVED');

    RETURN attendance.geo_ok('Office selection removed', attendance.employee_geo_location_json(p_id));
END;
$$;

-- ---------------------------------------------------------------------
-- 6 · Admin: review
-- ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION attendance.employee_geo_requests(
    p_status       varchar,   -- PENDING (default) | APPROVED | REJECTED | REVOKED | REMOVED | ALL
    p_office_id    varchar,
    p_employee_id  varchar,
    p_search       varchar,   -- emp_id prefix or name substring
    p_page         integer,
    p_limit        integer
) RETURNS jsonb
LANGUAGE plpgsql STABLE
AS $$
DECLARE
    v_status varchar := upper(btrim(COALESCE(NULLIF(btrim(p_status), ''), 'PENDING')));
    v_limit  integer := least(greatest(COALESCE(p_limit, 20), 1), 100);
    v_page   integer := greatest(COALESCE(p_page, 1), 1);
    v_search varchar := NULLIF(btrim(COALESCE(p_search, '')), '');
    v_total  bigint;
    v_items  jsonb;
BEGIN
    IF v_status NOT IN ('PENDING', 'APPROVED', 'REJECTED', 'REVOKED', 'REMOVED', 'ALL') THEN
        RETURN attendance.geo_fail('INVALID_INPUT',
            '`status` must be PENDING, APPROVED, REJECTED, REVOKED, REMOVED or ALL');
    END IF;

    WITH matched AS (
        SELECT egl.id, egl.requested_at, count(*) OVER () AS total
          FROM attendance.employee_geo_location egl
          JOIN attendance.geo_location_office g ON g.id = egl.geo_location_office_id
          LEFT JOIN LATERAL (SELECT name_en FROM attendance.employees
                              WHERE emp_id = egl.employee_id LIMIT 1) e ON true
         WHERE (v_status = 'ALL' OR egl.status = v_status)
           AND (NULLIF(btrim(COALESCE(p_office_id, '')), '') IS NULL OR g.office_id = btrim(p_office_id))
           AND (NULLIF(btrim(COALESCE(p_employee_id, '')), '') IS NULL OR egl.employee_id = btrim(p_employee_id))
           AND (v_search IS NULL
                OR egl.employee_id LIKE replace(replace(replace(v_search, '\', ''), '%', ''), '_', '\_') || '%'
                OR e.name_en ILIKE '%' || replace(replace(replace(v_search, '\', ''), '%', '\%'), '_', '\_') || '%')
         ORDER BY egl.requested_at, egl.id
         LIMIT v_limit OFFSET (v_page - 1) * v_limit
    )
    SELECT COALESCE(max(total), 0),
           COALESCE(jsonb_agg(attendance.employee_geo_location_json(id) ORDER BY requested_at, id), '[]'::jsonb)
      INTO v_total, v_items
      FROM matched;

    -- An out-of-range page has no rows to carry the window count; count directly.
    IF v_total = 0 AND v_page > 1 THEN
        SELECT count(*) INTO v_total
          FROM attendance.employee_geo_location egl
          JOIN attendance.geo_location_office g ON g.id = egl.geo_location_office_id
          LEFT JOIN LATERAL (SELECT name_en FROM attendance.employees
                              WHERE emp_id = egl.employee_id LIMIT 1) e ON true
         WHERE (v_status = 'ALL' OR egl.status = v_status)
           AND (NULLIF(btrim(COALESCE(p_office_id, '')), '') IS NULL OR g.office_id = btrim(p_office_id))
           AND (NULLIF(btrim(COALESCE(p_employee_id, '')), '') IS NULL OR egl.employee_id = btrim(p_employee_id))
           AND (v_search IS NULL
                OR egl.employee_id LIKE replace(replace(replace(v_search, '\', ''), '%', ''), '_', '\_') || '%'
                OR e.name_en ILIKE '%' || replace(replace(replace(v_search, '\', ''), '%', '\%'), '_', '\_') || '%');
    END IF;

    RETURN attendance.geo_ok('OK', jsonb_build_object(
        'items', v_items, 'total', v_total, 'page', v_page, 'limit', v_limit));
END;
$$;

-- One approve / reject / revoke. `p_action` is APPROVE | REJECT | REVOKE.
CREATE OR REPLACE FUNCTION attendance.employee_geo_review(
    p_id      bigint,
    p_action  varchar,
    p_note    varchar,
    p_actor   bigint
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_action  varchar := upper(btrim(COALESCE(p_action, '')));
    v_note    varchar := NULLIF(btrim(COALESCE(p_note, '')), '');
    v_new     varchar;
    v_from    varchar;
    v_old     varchar;
    v_office_status varchar;
BEGIN
    CASE v_action
        WHEN 'APPROVE' THEN v_new := 'APPROVED'; v_from := 'PENDING';
        WHEN 'REJECT'  THEN v_new := 'REJECTED'; v_from := 'PENDING';
        WHEN 'REVOKE'  THEN v_new := 'REVOKED';  v_from := 'APPROVED';
        ELSE RETURN attendance.geo_fail('INVALID_INPUT', '`action` must be APPROVE, REJECT or REVOKE');
    END CASE;

    IF v_action IN ('REJECT', 'REVOKE') AND (v_note IS NULL OR length(v_note) < 3) THEN
        RETURN attendance.geo_fail('REASON_REQUIRED', 'A reason (at least 3 characters) is required');
    END IF;
    IF length(v_note) > 255 THEN
        RETURN attendance.geo_fail('INVALID_INPUT', 'The note/reason must be at most 255 characters');
    END IF;

    SELECT egl.status, g.status INTO v_old, v_office_status
      FROM attendance.employee_geo_location egl
      JOIN attendance.geo_location_office g ON g.id = egl.geo_location_office_id
     WHERE egl.id = p_id
       FOR UPDATE OF egl;
    IF NOT FOUND THEN
        RETURN attendance.geo_fail('NOT_FOUND', format('Office selection %s not found', p_id),
                                   jsonb_build_object('id', p_id));
    END IF;
    IF v_old <> v_from THEN
        RETURN attendance.geo_fail('INVALID_STATUS_TRANSITION',
            format('Cannot %s a %s selection (only %s)', lower(v_action), v_old, v_from),
            jsonb_build_object('id', p_id, 'status', v_old));
    END IF;
    -- Approving a point nobody can check in at would only produce a confused employee.
    IF v_action = 'APPROVE' AND v_office_status <> 'ACTIVE' THEN
        RETURN attendance.geo_fail('GEO_LOCATION_OFFICE_INACTIVE',
            'This office geo-location is INACTIVE; activate it before approving',
            jsonb_build_object('id', p_id));
    END IF;

    UPDATE attendance.employee_geo_location
       SET status = v_new, reviewed_by = p_actor::text, reviewed_at = now(), review_note = v_note
     WHERE id = p_id;
    INSERT INTO attendance.employee_geo_location_audit
                (employee_geo_location_id, actor_id, action, old_status, new_status, note)
         VALUES (p_id, p_actor::text, v_action, v_old, v_new, v_note);

    RETURN attendance.geo_ok(format('Office selection %s', lower(v_new)),
                             attendance.employee_geo_location_json(p_id));
END;
$$;

-- Bulk review. Each id is reviewed on its own; one bad id does not undo the
-- rest, and the response says which succeeded and which failed and why.
CREATE OR REPLACE FUNCTION attendance.employee_geo_bulk_review(
    p_action  varchar,
    p_ids     bigint[],
    p_note    varchar,
    p_actor   bigint
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_ids  bigint[];
    v_id   bigint;
    v_res  jsonb;
    v_ok   jsonb := '[]'::jsonb;
    v_bad  jsonb := '[]'::jsonb;
BEGIN
    SELECT array_agg(DISTINCT x ORDER BY x) INTO v_ids FROM unnest(p_ids) x WHERE x IS NOT NULL;
    IF v_ids IS NULL THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`ids` must contain at least one id');
    END IF;
    IF array_length(v_ids, 1) > 200 THEN
        RETURN attendance.geo_fail('INVALID_INPUT', 'At most 200 ids per bulk review');
    END IF;
    IF upper(btrim(COALESCE(p_action, ''))) NOT IN ('APPROVE', 'REJECT', 'REVOKE') THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`action` must be APPROVE, REJECT or REVOKE');
    END IF;

    FOREACH v_id IN ARRAY v_ids LOOP
        v_res := attendance.employee_geo_review(v_id, p_action, p_note, p_actor);
        IF v_res->>'status' = 'success' THEN
            v_ok := v_ok || (v_res->'data');
        ELSE
            -- A missing reason fails every id identically: say it once.
            IF v_res->>'code' = 'REASON_REQUIRED' THEN RETURN v_res; END IF;
            v_bad := v_bad || jsonb_build_object('id', v_id, 'code', v_res->>'code', 'message', v_res->>'message');
        END IF;
    END LOOP;

    RETURN attendance.geo_ok(format('%s reviewed, %s failed', jsonb_array_length(v_ok), jsonb_array_length(v_bad)),
        jsonb_build_object('succeeded', v_ok, 'failed', v_bad));
END;
$$;

-- Admin assigns a point directly, already APPROVED. Works on any existing row
-- state (including REVOKED, which only an admin can restore). The employee
-- must exist; enrollment is not required, so staff can be set up in advance.
-- The per-employee limit is not applied: it guards self-service, not admins.
CREATE OR REPLACE FUNCTION attendance.employee_geo_assign(
    p_employee_id  varchar,
    p_geo_id       bigint,
    p_note         varchar,
    p_actor        bigint
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_emp   varchar := btrim(COALESCE(p_employee_id, ''));
    v_old   varchar;
    v_id    bigint;
    v_note  varchar := NULLIF(btrim(COALESCE(p_note, '')), '');
BEGIN
    IF NOT EXISTS (SELECT 1 FROM attendance.employees WHERE emp_id = v_emp) THEN
        RETURN attendance.geo_fail('EMPLOYEE_NOT_FOUND', format('Employee %s not found', v_emp));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM attendance.geo_location_office WHERE id = p_geo_id AND status = 'ACTIVE') THEN
        RETURN attendance.geo_fail('GEO_LOCATION_OFFICE_NOT_FOUND',
            format('Office geo-location %s does not exist or is inactive', p_geo_id));
    END IF;
    IF length(v_note) > 255 THEN
        RETURN attendance.geo_fail('INVALID_INPUT', 'The note must be at most 255 characters');
    END IF;

    PERFORM pg_advisory_xact_lock(hashtext('employee_geo_location:' || v_emp));

    SELECT id, status INTO v_id, v_old FROM attendance.employee_geo_location
     WHERE employee_id = v_emp AND geo_location_office_id = p_geo_id FOR UPDATE;
    IF v_old = 'APPROVED' THEN
        RETURN attendance.geo_fail('ALREADY_SELECTED', 'This office is already approved for the employee',
                                   attendance.employee_geo_location_json(v_id));
    END IF;

    INSERT INTO attendance.employee_geo_location
                (employee_id, geo_location_office_id, status, reviewed_by, reviewed_at, review_note)
         VALUES (v_emp, p_geo_id, 'APPROVED', p_actor::text, now(), v_note)
    ON CONFLICT (employee_id, geo_location_office_id) DO UPDATE
            SET status = 'APPROVED', reviewed_by = EXCLUDED.reviewed_by,
                reviewed_at = now(), review_note = EXCLUDED.review_note
      RETURNING id INTO v_id;

    INSERT INTO attendance.employee_geo_location_audit
                (employee_geo_location_id, actor_id, action, old_status, new_status, note)
         VALUES (v_id, p_actor::text, 'ASSIGN', v_old, 'APPROVED', v_note);

    RETURN attendance.geo_ok('Office assigned', attendance.employee_geo_location_json(v_id));
END;
$$;

