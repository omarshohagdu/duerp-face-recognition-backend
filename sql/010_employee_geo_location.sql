-- What an employee may pick: ACTIVE points only, without admin-only fields.
CREATE OR REPLACE FUNCTION attendance.geo_office_available()
RETURNS jsonb
LANGUAGE sql STABLE
AS $$
    SELECT attendance.geo_ok('OK', COALESCE(jsonb_agg(
               attendance.geo_office_json(g.id) - 'status' - 'created_by' - 'created_at' - 'updated_at'
               ORDER BY g.office_id, g.id), '[]'::jsonb))
      FROM attendance.geo_location_office g
     WHERE g.status = 'ACTIVE';
$$;

-- Is this person an employee with an active face enrollment?
-- Returns NULL when yes, or the failure envelope.
CREATE OR REPLACE FUNCTION attendance.geo_require_enrolled_employee(p_employee_id varchar)
RETURNS jsonb
LANGUAGE sql STABLE
AS $$
    SELECT CASE
        WHEN NOT EXISTS (SELECT 1 FROM attendance.employees WHERE emp_id = p_employee_id)
            THEN attendance.geo_fail('EMPLOYEE_NOT_FOUND',
                     'Only employees can select an office', jsonb_build_object('employee_id', p_employee_id))
        WHEN NOT EXISTS (SELECT 1 FROM attendance.wow_attendance_enrollments
                          WHERE person_id = p_employee_id AND id_type = 'Employee' AND is_active)
            THEN attendance.geo_fail('NOT_ENROLLED',
                     'Enroll your face first, then select your office', jsonb_build_object('employee_id', p_employee_id))
    END;
$$;

CREATE OR REPLACE FUNCTION attendance.employee_geo_select(
    p_employee_id  varchar,
    p_ids          bigint[]
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_emp      varchar := btrim(COALESCE(p_employee_id, ''));
    v_err      jsonb;
    v_ids      bigint[];
    v_bad      bigint;
    v_revoked  bigint;
    v_active   bigint[];
    v_new      bigint[];
    v_max      integer := attendance.geo_setting_int('GEO_MAX_ACTIVE_LOCATIONS', 5);
    v_gid      bigint;
    v_row      RECORD;
    v_out      jsonb := '[]'::jsonb;
BEGIN
    v_err := attendance.geo_require_enrolled_employee(v_emp);
    IF v_err IS NOT NULL THEN RETURN v_err; END IF;

    SELECT array_agg(DISTINCT x) INTO v_ids FROM unnest(p_ids) x WHERE x IS NOT NULL;
    IF v_ids IS NULL THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`geo_location_office_ids` must contain at least one id');
    END IF;
    IF array_length(v_ids, 1) > 50 THEN
        RETURN attendance.geo_fail('INVALID_INPUT', 'Too many ids in one request');
    END IF;

    -- Serialise selections per employee so two concurrent requests cannot both
    -- pass the limit check below.
    PERFORM pg_advisory_xact_lock(hashtext('employee_geo_location:' || v_emp));

    SELECT x INTO v_bad FROM unnest(v_ids) x
     WHERE NOT EXISTS (SELECT 1 FROM attendance.geo_location_office g WHERE g.id = x AND g.status = 'ACTIVE')
     LIMIT 1;
    IF v_bad IS NOT NULL THEN
        RETURN attendance.geo_fail('GEO_LOCATION_OFFICE_NOT_FOUND',
            format('Office geo-location %s does not exist or is inactive', v_bad),
            jsonb_build_object('geo_location_office_id', v_bad));
    END IF;

    SELECT COALESCE(array_agg(geo_location_office_id), '{}') INTO v_active
      FROM attendance.employee_geo_location
     WHERE employee_id = v_emp AND status IN ('PENDING', 'APPROVED');

    SELECT array_agg(x) INTO v_new FROM unnest(v_ids) x WHERE NOT (x = ANY (v_active));
    IF v_new IS NULL THEN
        RETURN attendance.geo_fail('ALREADY_SELECTED',
            'Every office in this request is already pending or approved for you');
    END IF;

    -- A revoked office is the admin's decision; only the admin can give it back
    -- (direct assign). Re-requesting it would just put it back in the queue.
    SELECT x INTO v_revoked FROM unnest(v_new) x
     WHERE EXISTS (SELECT 1 FROM attendance.employee_geo_location
                    WHERE employee_id = v_emp AND geo_location_office_id = x AND status = 'REVOKED')
     LIMIT 1;
    IF v_revoked IS NOT NULL THEN
        RETURN attendance.geo_fail('OFFICE_REVOKED',
            format('Office geo-location %s was revoked by an admin and cannot be re-requested', v_revoked),
            jsonb_build_object('geo_location_office_id', v_revoked));
    END IF;

    IF COALESCE(array_length(v_active, 1), 0) + array_length(v_new, 1) > v_max THEN
        RETURN attendance.geo_fail('LOCATION_LIMIT_EXCEEDED',
            format('You can hold at most %s pending or approved offices (you have %s)',
                   v_max, COALESCE(array_length(v_active, 1), 0)),
            jsonb_build_object('max', v_max, 'current', COALESCE(array_length(v_active, 1), 0)));
    END IF;

    FOREACH v_gid IN ARRAY v_new LOOP
        -- A REJECTED / REMOVED row goes back to PENDING rather than duplicating.
        INSERT INTO attendance.employee_geo_location (employee_id, geo_location_office_id, status)
             VALUES (v_emp, v_gid, 'PENDING')
        ON CONFLICT (employee_id, geo_location_office_id) DO UPDATE
                SET status = 'PENDING', requested_at = now(),
                    reviewed_by = NULL, reviewed_at = NULL, review_note = NULL
          RETURNING id, (xmax = 0) AS inserted INTO v_row;

        INSERT INTO attendance.employee_geo_location_audit
                    (employee_geo_location_id, actor_id, action, old_status, new_status)
             VALUES (v_row.id, v_emp, 'REQUEST', NULL, 'PENDING');

        v_out := v_out || attendance.employee_geo_location_json(v_row.id);
    END LOOP;

    RETURN attendance.geo_ok('Office selection sent for admin approval', v_out);
END;
$$;

