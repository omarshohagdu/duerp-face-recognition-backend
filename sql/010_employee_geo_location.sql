CREATE OR REPLACE FUNCTION attendance.geo_office_create(
    p_office_id     varchar,
    p_latitude      double precision,
    p_longitude     double precision,
    p_radius        integer,
    p_status        varchar,
    p_label         varchar,
    p_actor         bigint
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_office  varchar := btrim(COALESCE(p_office_id, ''));
    v_status  varchar := upper(btrim(COALESCE(p_status, 'ACTIVE')));
    v_radius  integer := COALESCE(p_radius, 100);
    v_id      bigint;
BEGIN
    IF v_office = '' THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`office_id` is required');
    END IF;
    IF p_latitude IS NULL OR p_latitude NOT BETWEEN -90 AND 90 THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`latitude` must be between -90 and 90');
    END IF;
    IF p_longitude IS NULL OR p_longitude NOT BETWEEN -180 AND 180 THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`longitude` must be between -180 and 180');
    END IF;
    IF v_radius NOT BETWEEN 30 AND 1000 THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`radius_meters` must be between 30 and 1000');
    END IF;
    IF v_status NOT IN ('ACTIVE', 'INACTIVE') THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`status` must be ACTIVE or INACTIVE');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM ictcell.body WHERE body_code = v_office) THEN
        RETURN attendance.geo_fail('OFFICE_NOT_FOUND',
            format('No office with code %s', v_office), jsonb_build_object('office_id', v_office));
    END IF;

    INSERT INTO attendance.geo_location_office
                (office_id, label, latitude, longitude, radius_meters, status, created_by)
         VALUES (v_office, NULLIF(btrim(COALESCE(p_label, '')), ''),
                 round(p_latitude::numeric, 7), round(p_longitude::numeric, 7),
                 v_radius, v_status, p_actor::text)
      RETURNING id INTO v_id;

    INSERT INTO attendance.geo_location_office_audit (geo_location_office_id, actor_id, action, new_value)
         VALUES (v_id, p_actor::text, 'CREATE', attendance.geo_office_json(v_id));

    RETURN attendance.geo_ok('Office geo-location created', attendance.geo_office_json(v_id));
END;
$$;

-- Any NULL argument leaves that field unchanged.
CREATE OR REPLACE FUNCTION attendance.geo_office_update(
    p_id         bigint,
    p_latitude   double precision,
    p_longitude  double precision,
    p_radius     integer,
    p_label      varchar,
    p_actor      bigint
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_old jsonb;
    v_new jsonb;
    v_linked integer;
BEGIN
    IF p_latitude IS NOT NULL AND p_latitude NOT BETWEEN -90 AND 90 THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`latitude` must be between -90 and 90');
    END IF;
    IF p_longitude IS NOT NULL AND p_longitude NOT BETWEEN -180 AND 180 THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`longitude` must be between -180 and 180');
    END IF;
    IF p_radius IS NOT NULL AND p_radius NOT BETWEEN 30 AND 1000 THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`radius_meters` must be between 30 and 1000');
    END IF;
    IF p_latitude IS NULL AND p_longitude IS NULL AND p_radius IS NULL AND p_label IS NULL THEN
        RETURN attendance.geo_fail('INVALID_INPUT',
            'Nothing to update: send at least one of latitude, longitude, radius_meters, label');
    END IF;

    PERFORM 1 FROM attendance.geo_location_office WHERE id = p_id FOR UPDATE;
    IF NOT FOUND THEN
        RETURN attendance.geo_fail('NOT_FOUND', format('Office geo-location %s not found', p_id));
    END IF;
    v_old := attendance.geo_office_json(p_id);

    UPDATE attendance.geo_location_office
       SET latitude      = COALESCE(round(p_latitude::numeric, 7),  latitude),
           longitude     = COALESCE(round(p_longitude::numeric, 7), longitude),
           radius_meters = COALESCE(p_radius, radius_meters),
           -- '' clears the label; NULL leaves it alone.
           label         = CASE WHEN p_label IS NULL THEN label
                                ELSE NULLIF(btrim(p_label), '') END,
           updated_at    = now()
     WHERE id = p_id;

    v_new := attendance.geo_office_json(p_id);
    IF v_new - 'updated_at' IS DISTINCT FROM v_old - 'updated_at' THEN
        INSERT INTO attendance.geo_location_office_audit
                    (geo_location_office_id, actor_id, action, old_value, new_value)
             VALUES (p_id, p_actor::text, 'UPDATE', v_old, v_new);
    END IF;

    SELECT count(*) INTO v_linked FROM attendance.employee_geo_location
     WHERE geo_location_office_id = p_id AND status IN ('PENDING', 'APPROVED');

    RETURN attendance.geo_ok('Office geo-location updated',
        v_new || jsonb_build_object('linked_employees', v_linked));
END;
$$;

CREATE OR REPLACE FUNCTION attendance.geo_office_set_status(
    p_id      bigint,
    p_status  varchar,
    p_actor   bigint
) RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_status varchar := upper(btrim(COALESCE(p_status, '')));
    v_old    varchar;
    v_affected integer;
BEGIN
    IF v_status NOT IN ('ACTIVE', 'INACTIVE') THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`status` must be ACTIVE or INACTIVE');
    END IF;

    SELECT status INTO v_old FROM attendance.geo_location_office WHERE id = p_id FOR UPDATE;
    IF NOT FOUND THEN
        RETURN attendance.geo_fail('NOT_FOUND', format('Office geo-location %s not found', p_id));
    END IF;

    IF v_old <> v_status THEN
        UPDATE attendance.geo_location_office SET status = v_status, updated_at = now() WHERE id = p_id;
        INSERT INTO attendance.geo_location_office_audit
                    (geo_location_office_id, actor_id, action, old_value, new_value)
             VALUES (p_id, p_actor::text, 'STATUS',
                     jsonb_build_object('status', v_old), jsonb_build_object('status', v_status));
    END IF;

    -- Employees whose APPROVED selection this blocks/unblocks — the "office
    -- deactivated" notification goes to these.
    SELECT count(*) INTO v_affected FROM attendance.employee_geo_location
     WHERE geo_location_office_id = p_id AND status = 'APPROVED';

    RETURN attendance.geo_ok(
        CASE WHEN v_old = v_status THEN format('Already %s', v_status)
             ELSE format('Office geo-location set %s', v_status) END,
        attendance.geo_office_json(p_id) || jsonb_build_object('approved_employees', v_affected));
END;
$$;

-- Admin list: every status unless filtered, with how many employees are approved on each point.
CREATE OR REPLACE FUNCTION attendance.geo_office_list(
    p_office_id varchar,
    p_status    varchar
) RETURNS jsonb
LANGUAGE plpgsql STABLE
AS $$
DECLARE
    v_status varchar := NULLIF(upper(btrim(COALESCE(p_status, ''))), '');
BEGIN
    IF v_status IS NOT NULL AND v_status NOT IN ('ACTIVE', 'INACTIVE') THEN
        RETURN attendance.geo_fail('INVALID_INPUT', '`status` must be ACTIVE or INACTIVE');
    END IF;

    RETURN attendance.geo_ok('OK', COALESCE((
        SELECT jsonb_agg(attendance.geo_office_json(g.id) || jsonb_build_object(
                   'approved_employees', (SELECT count(*) FROM attendance.employee_geo_location egl
                                           WHERE egl.geo_location_office_id = g.id AND egl.status = 'APPROVED'),
                   'pending_employees',  (SELECT count(*) FROM attendance.employee_geo_location egl
                                           WHERE egl.geo_location_office_id = g.id AND egl.status = 'PENDING'))
                 ORDER BY g.office_id, g.id)
          FROM attendance.geo_location_office g
         WHERE (NULLIF(btrim(COALESCE(p_office_id, '')), '') IS NULL OR g.office_id = btrim(p_office_id))
           AND (v_status IS NULL OR g.status = v_status)
    ), '[]'::jsonb));
END;
$$;

